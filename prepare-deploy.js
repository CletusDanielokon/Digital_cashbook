// =====================================================
// prepare-deploy.js
// Builds a clean "deploy" folder with ONLY the frontend files,
// pointed at your online backend. Your original files are not changed.
//
// Usage (run in the project folder, next to index.html):
//     node prepare-deploy.js https://your-backend.onrender.com https://your-site.netlify.app
//
// The second address (your Netlify site) is optional but needed for SEO:
// it adds the canonical link, absolute share-image address, robots.txt and sitemap.xml.
// =====================================================
const fs = require("fs");
const path = require("path");

const apiOrigin = (process.argv[2] || "").trim().replace(/\/+$/, "");

const siteOrigin = (process.argv[3] || "").trim().replace(/\/+$/, "");

if (!/^https:\/\/[^\s/]+$/.test(apiOrigin)) {
    console.error("\nPlease give your backend address, for example:");
    console.error("  node prepare-deploy.js https://cashbook-api.onrender.com https://my-cashbook.netlify.app\n");
    process.exit(1);
}

if (siteOrigin && !/^https:\/\/[^\s/]+$/.test(siteOrigin)) {
    console.error("\nThe website address (second one) must look like https://my-cashbook.netlify.app\n");
    process.exit(1);
}

const root = __dirname;
const out = path.join(root, "deploy");

// Never copy these (backend holds your secrets in backend/.env)
const SKIP_DIRS = new Set(["node_modules", "backend", ".git", ".dist", "deploy"]);
const SKIP_FILES = new Set([
    "prepare-deploy.js", "package.json", "package-lock.json", "README.md",
    ".gitignore", ".env", "SETUP-AND-HOSTING.md"
]);
const KEEP_EXT = new Set([
    ".html", ".js", ".css", ".png", ".jpg", ".jpeg", ".gif", ".svg",
    ".ico", ".webp", ".woff", ".woff2", ".ttf"
]);

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out);

let copied = 0;
const htmlFiles = [];

function copyDir(from, to) {
    for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
        const src = path.join(from, entry.name);
        const dest = path.join(to, entry.name);

        if (entry.isDirectory()) {
            if (SKIP_DIRS.has(entry.name)) continue;
            fs.mkdirSync(dest, { recursive: true });
            copyDir(src, dest);
        } else {
            if (SKIP_FILES.has(entry.name)) continue;
            if (!KEEP_EXT.has(path.extname(entry.name).toLowerCase())) continue;
            fs.copyFileSync(src, dest);
            copied++;
            if (dest.toLowerCase().endsWith(".html")) htmlFiles.push(dest);
        }
    }
}

copyDir(root, out);

// config.js: when the site is NOT running on your own computer, every request
// that points at http://localhost:5000 is sent to the online backend instead.
const config = `// Generated by prepare-deploy.js
(function () {
    var LOCAL_API = "http://localhost:5000";
    var ONLINE_API = ${JSON.stringify(apiOrigin)};
    var host = window.location.hostname;

    // On your own computer keep using the local backend
    if (host === "localhost" || host === "127.0.0.1") return;

    var originalFetch = window.fetch;

    window.fetch = function (input, init) {
        if (typeof input === "string" && input.indexOf(LOCAL_API) === 0) {
            input = ONLINE_API + input.slice(LOCAL_API.length);
        }
        return originalFetch.call(this, input, init);
    };
})();
`;
fs.writeFileSync(path.join(out, "config.js"), config);

// Load config.js first on every page
let injected = 0;
for (const file of htmlFiles) {
    let html = fs.readFileSync(file, "utf8");
    if (html.includes('src="config.js"')) continue;

    const updated = html.replace(/<head[^>]*>/i, (tag) => `${tag}\n    <script src="config.js"></script>`);

    if (updated !== html) {
        fs.writeFileSync(file, updated);
        injected++;
    }
}


// ---------- SEO: needs the real website address ----------
const publicPages = ["index.html"];   // only pages that should appear in Google
let seoDone = false;

const indexPath = path.join(out, "index.html");

if (fs.existsSync(indexPath)) {
    let html = fs.readFileSync(indexPath, "utf8");

    if (siteOrigin) {
        html = html.split("__SITE_URL__").join(siteOrigin);
        html = html.replace(/(<meta (?:property="og:image"|name="twitter:image") content=")og-image\.png(")/g, "$1" + siteOrigin + "/og-image.png$2");

        const extra =
            '    <link rel="canonical" href="' + siteOrigin + '/">\n' +
            '    <meta property="og:url" content="' + siteOrigin + '/">\n';
        html = html.replace(/<\/head>/i, extra + "</head>");

        fs.writeFileSync(path.join(out, "robots.txt"),
            "User-agent: *\nAllow: /\n\nSitemap: " + siteOrigin + "/sitemap.xml\n");

        const today = new Date().toISOString().slice(0, 10);
        fs.writeFileSync(path.join(out, "sitemap.xml"),
            '<?xml version="1.0" encoding="UTF-8"?>\n' +
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
            '  <url>\n    <loc>' + siteOrigin + '/</loc>\n    <lastmod>' + today + '</lastmod>\n  </url>\n' +
            '</urlset>\n');

        seoDone = true;
    } else {
        // No address given: drop the placeholder line so the page data stays valid
        html = html.replace(/\s*"url": "__SITE_URL__\/",/, "");
    }

    fs.writeFileSync(indexPath, html);
}

// Safety checks
const leftovers = [];
let total = 0;
(function scan(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, entry.name);
        if (entry.isDirectory()) { scan(p); continue; }
        if (!/\.(html|js)$/i.test(entry.name) || entry.name === "config.js") continue;
        total++;
        const text = fs.readFileSync(p, "utf8");
        const found = text.match(/https?:\/\/(localhost|127\.0\.0\.1)(:\d+)?[^\s"'`)]*/g) || [];
        for (const url of found) {
            if (!url.startsWith("http://localhost:5000")) leftovers.push(`${path.relative(out, p)}: ${url}`);
        }
    }
})(out);

// Google sign-in needs the real Client ID in auth-extra.js
const authExtra = path.join(out, "auth-extra.js");
const clientIdMissing = fs.existsSync(authExtra) &&
    fs.readFileSync(authExtra, "utf8").includes("PASTE_YOUR_GOOGLE_CLIENT_ID_HERE");

const hasEnv = fs.existsSync(path.join(out, ".env")) || fs.existsSync(path.join(out, "backend"));

console.log("\nDeploy folder ready: " + out);
console.log("  files copied:        " + copied + " (+ config.js)");
console.log("  pages with config.js: " + injected + " of " + htmlFiles.length);
console.log("  backend address:     " + apiOrigin);
console.log("  website address:    " + (siteOrigin || "(not given: SEO links, robots.txt and sitemap.xml were skipped)"));
console.log("  secrets/backend in folder: " + (hasEnv ? "YES - STOP, DO NOT UPLOAD" : "no (good)"));
if (!siteOrigin) {
    console.log("\nSEO tip: run it again with your Netlify address as the second value to add the");
    console.log("  canonical link, share image address, robots.txt and sitemap.xml:");
    console.log("  node prepare-deploy.js " + apiOrigin + " https://YOUR-SITE.netlify.app");
}
if (clientIdMissing) {
    console.log("\nWARNING: auth-extra.js still has the placeholder Google Client ID.");
    console.log("  Paste your real Client ID at the top of auth-extra.js, then run this command again,");
    console.log("  otherwise the Google button will not work on the live site.");
}
if (leftovers.length) {
    console.log("\nCheck these other local addresses (they will not be redirected):");
    leftovers.forEach((l) => console.log("  " + l));
}
console.log("\nNext: drag the 'deploy' folder onto https://app.netlify.com/drop\n");
